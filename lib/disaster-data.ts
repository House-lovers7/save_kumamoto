/**
 * 直近の巡回時刻。毎日の再確認巡回（docs/OPERATIONS.md 第5章）では、公式ページを実際に開き直した
 * うえで、この2つだけを書き換える。**再確認せずにここを進めることは鮮度の捏造であり禁止**。
 * 期限は確認から24時間。
 */
const PATROL_AT = "2026-08-01T09:30:00+09:00";
const PATROL_EXPIRES_AT = "2026-08-02T09:30:00+09:00";

/**
 * 巡回で確認した1カード分の時刻。
 *
 * publishedAt は出典ページに表示されている最終更新日。日付しか出ていないページは 00:00 へ
 * 切り下げる（鮮度を実際より新しく見せないための保守側の値）。
 *
 * sourceStatus に "unavailable" を渡すのは、リンクは生きているがカードの手順を実行するための
 * 情報がそのページに無いとき。このとき ActionCard.unverified で何が無いのかを必ず書く。
 */
const patrolled = (publishedAt: string, sourceStatus: SourceStatus = "official") => ({
  publishedAt,
  fetchedAt: PATROL_AT,
  checkedAt: PATROL_AT,
  expiresAt: PATROL_EXPIRES_AT,
  sourceStatus,
});

